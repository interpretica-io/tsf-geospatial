# Generate the uniform RPC boilerplate from one list: the XDR
# definitions (rpcs_geospatial/geospatial.x.m4), the RPC server
# functions (rpcs_geospatial/rpcs_geospatial.c) and the client calls
# (tapi_geospatial/tapi_geo_rpc_gen.h). The list must be in the order
# of ta_geo_op in ta_geospatial/ta_geo_core.h. Run from the repository
# root after changing it; the outputs are committed.
import os

OPS = [
    ("available", "engine versions, features bitmask, GDAL drivers"),
    ("config", "set the limits (max_vertices, max_depth, ...)"),
    ("stats", "objects alive, operations run, process memory"),
    ("release", "release the objects ha (and hb)"),
    ("geom_parse", "parse text (kind = wkt|ewkt|wkb|ewkb|geojson|auto)"),
    ("geom_info", "type, dimensions, CRS, counts, bounds of ha"),
    ("geom_serialize", "ha as kind = wkt|wkb|ewkb|geojson, in report"),
    ("geom_derive", "centroid, envelope, boundary, ... of ha"),
    ("geom_check", "validate ha (kind = all|validity|...); never repairs"),
    ("geom_repair", "an explicitly repaired copy of ha"),
    ("geom_predicate", "DE-9IM predicate kind of (ha, hb)"),
    ("geom_construct", "overlay, buffer, simplify of ha (, hb)"),
    ("geom_measure", "distance, length, area, perimeter; planar or geodesic"),
    ("crs_info", "lookup, validate, compare reference systems"),
    ("transform", "transform geometry ha; operation metadata in result"),
    ("transform_coords", "transform coordinate lines in text"),
    ("transform_bounds", "transform a bounding box"),
    ("ds_open", "open a vector or raster dataset (path in text)"),
    ("ds_info", "layers, schema, count, extent, crs of dataset ha"),
    ("ds_fetch", "bounded features of ha, or one geometry as a handle"),
    ("ds_validate", "stream-validate a layer of ha"),
    ("ds_compare", "compare layers of ha and hb by identifier"),
    ("ds_write", "write a generated dataset or a copy of ha"),
    ("raster_info", "raster metadata of ha"),
    ("raster_read", "a window of pixels of ha"),
    ("raster_stats", "tiled statistics of a band of ha"),
    ("raster_compare", "tiled comparison of rasters ha and hb"),
    ("raster_write", "write a synthetic raster"),
    ("track_load", "load observations from text or dataset ha"),
    ("track_eval", "evaluate track ha (against hb)"),
    ("gen", "deterministic test geometries"),
    ("ogc", "OGC service checks at the URL in text"),
    ("perf", "timed loops on the agent, cold and warm"),
]

HDR = """/* SPDX-License-Identifier: MIT */
/* Copyright (C) 2026 Interpretica, Unipessoal Lda. All rights reserved. */
"""

def xdr():
    out = [HDR, """/** @file
 * @brief RPC for geospatial processing
 *
 * Generated by ci/gen-rpc.py; edit the list there.
 *
 * The geo_* RPCs of rpcs_geospatial, a thin layer over ta_geospatial.
 * Add this file to the rpcxdr definitions of the engine platform and of
 * the agent platform:
 *
 *   TE_LIB_PARMS([rpcxdr], [<platform>], [],
 *                [--with-rpcdefs=tarpc_job.x.m4,../rpcs_geospatial/geospatial.x.m4])
 *
 * Every RPC has the same shape: two object handles, a sub-operation
 * (kind), an input text and options ("key=value" lines); back come a
 * return code, a new handle, a feature bitmask and three strings - the
 * result ("key=value" lines), the report (records of tab-separated,
 * percent-escaped fields) and the reason of a failure. XDR has no
 * portable floating-point type: real numbers travel in the text,
 * printed with 17 significant digits. Geometries, datasets and tracks
 * stay on the agent; only handles, results and bounded reports cross.
 *
 * Field names avoid the RPC language's keywords ("version", "program",
 * "string").
 */
"""]
    for name, doc in OPS:
        out.append(f"""
/* geo_{name}(): {doc}. */
struct tarpc_geo_{name}_in {{
    struct tarpc_in_arg common;

    tarpc_int       ha;
    tarpc_int       hb;
    string          kind<>;
    string          text<>;
    string          params<>;
}};

struct tarpc_geo_{name}_out {{
    struct tarpc_out_arg common;

    tarpc_int       retval;
    tarpc_int       handle;
    tarpc_uint      features;
    string          result<>;
    string          report<>;
    string          errmsg<>;
}};
""")
    out.append("\nprogram geospatial\n{\n    version ver0\n    {\n")
    for name, _ in OPS:
        out.append(f"        RPC_DEF(geo_{name})\n")
    out.append("    } = 1;\n} = 49;\n")
    return "".join(out)

def rpcs():
    out = [HDR, """/** @file
 * @brief Geospatial RPC server library
 *
 * Generated by ci/gen-rpc.py; edit the list there.
 *
 * The geo_* RPCs (see geospatial.x.m4) on top of ta_geospatial. Every
 * RPC has the same shape, so each is one plain C function naming its
 * operation, and the TARPC_FUNC_STATIC() wrapper after it moves the
 * strings ta_geo_rpc() returns straight into the out structure (XDR
 * frees them after sending). The work happens on the agent, in the RPC
 * server process.
 */

#define TE_LGR_USER     "RPC GEO"

#include "te_config.h"

#include <string.h>

#include "te_defs.h"
#include "te_errno.h"
#include "rpc_server.h"

#include "ta_geo.h"
"""]
    for name, _ in OPS:
        op = "TA_GEO_OP_" + name.upper()
        out.append(f"""
/* ---- {name} {'-' * (60 - len(name))} */

static te_errno
geo_{name}(int ha, int hb, const char *kind, const char *text,
     {' ' * len(name)}const char *params, int *handle, unsigned int *features,
     {' ' * len(name)}char **result, char **report, char **errmsg)
{{
    return ta_geo_rpc({op}, ha, hb, kind, text, params, handle,
                      features, result, report, errmsg);
}}

TARPC_FUNC_STATIC(geo_{name}, {{}},
{{
    int handle = 0;
    unsigned int features = 0;

    MAKE_CALL(out->retval = func(in->ha, in->hb, in->kind, in->text,
                                 in->params, &handle, &features,
                                 &out->result, &out->report, &out->errmsg));
    out->handle = handle;
    out->features = features;
    out->common.errno_changed = false;
}})
""")
    return "".join(out)

def tapi():
    out = [HDR, """/** @file
 * @brief Geospatial TAPI: generated RPC client table
 *
 * Generated by ci/gen-rpc.py; edit the list there. Included once, by
 * tapi_geo_rpc.c.
 */

"""]
    for name, _ in OPS:
        out.append(f"GEO_RPC(geo_{name})\n")
    out.append("\nstatic const struct {\n    const char *name;\n"
               "    te_errno (*call)(rcf_rpc_server *, const tapi_geo_rpc_args *,\n"
               "                     tapi_geo_rpc_res *);\n} geo_rpcs[] = {\n")
    for name, _ in OPS:
        out.append(f"    {{ \"geo_{name}\", call_geo_{name} }},\n")
    out.append("};\n")
    return "".join(out)

def enum():
    out = ["/* Generated by ci/gen-rpc.py: the geo_* RPCs, in wire order. */\n"]
    for name, _ in OPS:
        out.append(f"    TAPI_GEO_RPC_{name.upper()},\n")
    return "".join(out)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
for path, text in [("rpcs_geospatial/geospatial.x.m4", xdr()),
                   ("rpcs_geospatial/rpcs_geospatial.c", rpcs()),
                   ("tapi_geospatial/tapi_geo_rpc_gen.h", tapi()),
                   ("tapi_geospatial/tapi_geo_rpc_ops.h", enum())]:
    with open(os.path.join(root, path), "w") as f:
        f.write(text)
    print("wrote", path)
